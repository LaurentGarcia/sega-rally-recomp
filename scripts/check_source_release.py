#!/usr/bin/env python3
"""Check a Git source tree and optional export against a bounded file manifest.

This is an artifact-boundary check, not a legal or security certification.
It checks one tree (HEAD by default); historical auditing is separate.
Exports must contain exactly the tree's regular file paths and bytes. Git file
modes are recorded, but export permission bits are not compared.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import re
import subprocess
import tarfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
MAX_FILES = 20_000
MAX_FILE = 16 * 1024 * 1024
MAX_TOTAL = 128 * 1024 * 1024
GRADLE_PATH = "platform/mobile/android/gradle/wrapper/gradle-wrapper.jar"
GRADLE_SHA256 = "498495120a03b9a6ab5d155f5de3c8f0d986a449153702fb80fc80e134484f17"
# Only explicitly selected promotional images; all other capture/image paths
# remain forbidden. Provenance is documented beside the curated files.
CURATED_SCREENSHOTS: dict[str, str] = {
    'docs/images/hero.png': '80119f52162b2249459b67a5bb8ad3fe5724fb6b0cea4913f95bff1deebfabd0',
    'docs/images/forest.png': '9ad7f662b6d2c7d62b1c17c2fb094a2655a0938269ed566c8a96a9a6a6151a01',
    'docs/images/mountain.png': '005bfe587184233f00d62b03b5da3f9e9e9d33017896c5684bb56417249b1b44',
    'docs/images/finish.png': '7cc3f11cf43021a69f3e6847bee571c05b756fa6c76443ebe508ac54d2838b96',
}
SHADER_PATH = "src/app/gpu/shaders_gen.h"
SHADER_HEADERS = (
    b"// Generated by scripts/build_shaders.py from src/app/gpu/m2.hlsl:",
    b"// Generated by isolated build.py from common HLSL; diagnostic only.",
)
FORBIDDEN_PARTS = {
    "rom", "roms", "firmware", "generated", "extracted", "captures", "dumps",
    "traces", "private", "build", "logs", "cmakefiles", ".git", ".aws", ".ssh",
}
FORBIDDEN_SUFFIX = re.compile(
    r"\.(?:zip|7z|rar|tar|gz|xz|rom|bin|ic\d+|chd|iso|png|jpe?g|gif|bmp|tga|ppm|"
    r"wav|mp3|ogg|f32le|m2tr|m2in|apk|ipa|exe|dll|dylib|so|a|o|jar|"
    r"pem|key|p8|p12|pfx|keystore|mobileprovision)$", re.I)
GENERATED_NAME = re.compile(r"^(?:chunk_\d+\.(?:cpp|h)|gen_table\.(?:cpp|h)|snd_gen\.cpp)$", re.I)
SECRET_RULES = {
    "private-key header": rb"-----BEGIN (?:RSA |EC |DSA |OPENSSH |ENCRYPTED )?PRIVATE KEY-----",
    "AWS access identifier": rb"\b(?:AKIA|ASIA)[A-Z0-9]{16}\b",
    "GitHub token": rb"\b(?:gh[pousr]_[A-Za-z0-9]{36}|github_pat_[A-Za-z0-9_]{40,})\b",
    "Slack token": rb"\bxox[baprs]-[A-Za-z0-9-]{20,}\b",
    "Google API key": rb"\bAIza[A-Za-z0-9_-]{35}\b",
    "OpenAI key": rb"\bsk-(?:proj-)?[A-Za-z0-9_-]{25,}\b",
}
GAME_GENERATED = re.compile(
    rb"(?m)^\s*// Generated by (?:m2recomp|m2sndrecomp|m2tgprecomp)\b|"
    rb"(?m:^\s*(?:(?:static|inline)\s+)*(?:void|bool|int|uint32_t)\s+"
    rb"(?:native_[0-9a-fA-F]{5,}|fn_[0-9a-fA-F]{5,})\s*\()")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def canonical(value: dict) -> bytes:
    return (json.dumps(value, sort_keys=True, separators=(",", ":")) + "\n").encode()


def git(repo: Path, *args: str, data: bytes | None = None) -> bytes:
    result = subprocess.run(["git", "-C", str(repo), *args], input=data,
                            capture_output=True, timeout=30)
    if result.returncode:
        raise ValueError("Git tree query failed")
    return result.stdout


def checked_path(name: str) -> str:
    path = PurePosixPath(name)
    if (not name or len(name.encode()) > 1024 or "\\" in name or name.startswith("/") or
            any(part in ("", ".", "..") for part in name.split("/"))):
        raise ValueError(f"unsafe export path: {name!r}")
    if path.as_posix() != name:
        raise ValueError(f"noncanonical export path: {name!r}")
    return name


def classify(name: str, data: bytes) -> str:
    checked_path(name)
    path = PurePosixPath(name)
    parts = [part.lower() for part in path.parts]
    if (any(part in FORBIDDEN_PARTS or part.endswith((".app", ".xcarchive")) or
            part.startswith("build-") for part in parts) or
            path.name.lower().startswith(".env") or
            path.name.lower() in {"id_rsa", "id_ed25519", "credentials"}):
        raise ValueError(f"private or generated-output path: {name}")
    if name in CURATED_SCREENSHOTS:
        if sha256(data) != CURATED_SCREENSHOTS[name]:
            raise ValueError(f'unreviewed screenshot bytes: {name}')
        return "curated_documentation_screenshot"
    if name == GRADLE_PATH:
        if sha256(data) != GRADLE_SHA256:
            raise ValueError(f"unreviewed Gradle wrapper bytes: {name}")
        return "reviewed_gradle_wrapper_apache2"
    if FORBIDDEN_SUFFIX.search(name) or GENERATED_NAME.fullmatch(path.name):
        raise ValueError(f"ROM, binary, capture or generated-output filename: {name}")
    if b"\0" in data or data.startswith((b"PK\x03\x04", b"\x7fELF", b"!<arch>\n", b"MZ")):
        raise ValueError(f"unreviewed binary content: {name}")
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        raise ValueError(f"unreviewed non-UTF8 content: {name}") from None
    for label, pattern in SECRET_RULES.items():
        if re.search(pattern, data):
            raise ValueError(f"credential marker ({label}) in {name}")
    if GAME_GENERATED.search(data):
        raise ValueError(f"game-derived generation marker in {name}")
    if name == SHADER_PATH:
        if not data.startswith(SHADER_HEADERS):
            raise ValueError(f"missing project shader provenance marker: {name}")
        return "project_hlsl_shader_header"
    return "source_or_text_metadata"


def source_manifest(repo: Path, ref: str = "HEAD") -> dict:
    tree = git(repo, "rev-parse", "--verify", "--end-of-options", f"{ref}^{{tree}}").decode().strip()
    revision = git(repo, "rev-parse", "--verify", "--end-of-options", ref).decode().strip()
    entries = []
    for row in git(repo, "ls-tree", "-r", "-z", tree).split(b"\0"):
        if not row:
            continue
        meta, raw_name = row.split(b"\t", 1)
        mode, kind, oid = meta.decode().split()
        name = checked_path(raw_name.decode("utf-8"))
        if kind != "blob" or mode not in ("100644", "100755"):
            raise ValueError(f"source export requires regular files: {name}")
        entries.append((name, mode, oid))
    if len(entries) > MAX_FILES:
        raise ValueError("source file-count limit")
    oids = sorted({entry[2] for entry in entries})
    request = ("\n".join(oids) + "\n").encode()
    metadata = git(repo, "cat-file", "--batch-check=%(objectname) %(objecttype) %(objectsize)", data=request)
    sizes = {row.split()[0].decode(): int(row.split()[2]) for row in metadata.splitlines()}
    if (any(n > MAX_FILE for n in sizes.values()) or
            sum(sizes[oid] for _, _, oid in entries) > MAX_TOTAL):
        raise ValueError("source byte-size limit")
    raw = git(repo, "cat-file", "--batch", data=request)
    blobs, position = {}, 0
    for oid in oids:
        end = raw.index(b"\n", position)
        found, kind, length = raw[position:end].decode().split()
        length = int(length)
        if found != oid or kind != "blob" or length != sizes[oid]:
            raise ValueError("unexpected Git blob response")
        blobs[oid] = raw[end + 1:end + 1 + length]
        position = end + 2 + length
    files = [{"path": name, "mode": mode, "git_blob": oid,
              "bytes": len(blobs[oid]), "sha256": sha256(blobs[oid]),
              "classification": classify(name, blobs[oid])}
             for name, mode, oid in sorted(entries)]
    return {"schema": 1, "revision": revision, "git_tree": tree, "files": files}


def check_files(manifest: dict, files: dict[str, bytes]) -> None:
    expected = {row["path"]: row for row in manifest["files"]}
    if set(files) != set(expected):
        raise ValueError("export paths differ: " + json.dumps({
            "extra": sorted(set(files) - set(expected)),
            "missing": sorted(set(expected) - set(files))}))
    for name, data in files.items():
        row = expected[name]
        if len(data) != row["bytes"] or sha256(data) != row["sha256"]:
            raise ValueError(f"export bytes differ: {name}")


def directory_files(directory: Path) -> dict[str, bytes]:
    files, total, count = {}, 0, 0
    def visit(folder: Path):
        nonlocal total, count
        for path in sorted(folder.iterdir()):
            count += 1
            if count > MAX_FILES * 2:
                raise ValueError("export entry-count limit")
            if path.is_symlink():
                raise ValueError("export symlink rejected")
            if path.is_dir():
                classify(path.relative_to(directory).as_posix() + "/.source-check", b"")
                visit(path)
            elif path.is_file():
                name = checked_path(path.relative_to(directory).as_posix())
                n = path.stat().st_size
                total += n
                if n > MAX_FILE or total > MAX_TOTAL or len(files) >= MAX_FILES:
                    raise ValueError("export limits exceeded")
                files[name] = path.read_bytes()
            else:
                raise ValueError("export special file rejected")
    visit(directory)
    return files


def archive_files(path: Path, expected: set[str]) -> tuple[dict[str, bytes], str]:
    if path.stat().st_size > MAX_TOTAL:
        raise ValueError("archive byte-size limit")
    raw = path.read_bytes()
    files, total, count = {}, 0, 0
    def read_member(stream, size):
        with stream:
            return stream.read(size + 1)
    def add(name: str, size: int, read):
        nonlocal total, count
        checked_path(name)
        count += 1
        total += size
        if count > MAX_FILES or size > MAX_FILE or total > MAX_TOTAL:
            raise ValueError("archive limits exceeded")
        if name in files:
            raise ValueError("duplicate archive member")
        data = read()
        if len(data) != size:
            raise ValueError("archive member size mismatch")
        files[name] = data
    if zipfile.is_zipfile(io.BytesIO(raw)):
        with zipfile.ZipFile(io.BytesIO(raw)) as archive:
            if len(archive.infolist()) > MAX_FILES * 2:
                raise ValueError("archive entry-count limit")
            for entry in archive.infolist():
                kind = (entry.external_attr >> 16) & 0o170000
                if entry.is_dir():
                    if kind not in (0, 0o040000) or entry.file_size:
                        raise ValueError("archive directory has invalid type or payload")
                    classify(entry.filename.rstrip("/") + "/.source-check", b"")
                    continue
                if kind not in (0, 0o100000):
                    raise ValueError("archive link or special file rejected")
                add(entry.filename, entry.file_size,
                    lambda e=entry: read_member(archive.open(e), e.file_size))
    else:
        with tarfile.open(fileobj=io.BytesIO(raw), mode="r:*") as archive:
            for number, entry in enumerate(archive, 1):
                if number > MAX_FILES * 2:
                    raise ValueError("archive entry-count limit")
                if entry.isdir():
                    if entry.size:
                        raise ValueError("archive directory has payload")
                    classify(entry.name.rstrip("/") + "/.source-check", b"")
                    continue
                if not entry.isfile():
                    raise ValueError("archive link or special file rejected")
                add(entry.name, entry.size,
                    lambda e=entry: read_member(archive.extractfile(e), e.size))
    if set(files) != expected:
        prefixes = {name.split("/", 1)[0] for name in files}
        if len(prefixes) == 1 and all("/" in name for name in files):
            files = {name.split("/", 1)[1]: data for name, data in files.items()}
    return files, sha256(raw)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=ROOT)
    parser.add_argument("--ref", default="HEAD")
    parser.add_argument("--export-dir", type=Path)
    parser.add_argument("--archive", type=Path)
    parser.add_argument("--output", type=Path, help="New manifest/report file; never overwritten")
    args = parser.parse_args(argv)
    try:
        manifest = source_manifest(args.repo, args.ref)
        identity = sha256(canonical(manifest))
        report = {"status": "PASS", "scope": "one Git tree; historical audit separate; no legal/security certification",
                  "manifest_sha256": identity, "manifest": manifest}
        if args.export_dir:
            check_files(manifest, directory_files(args.export_dir))
            report["export_content_verified"] = True
        if args.archive:
            files, digest = archive_files(args.archive, {row["path"] for row in manifest["files"]})
            check_files(manifest, files)
            report["archive"] = {"sha256": digest, "bytes": args.archive.stat().st_size,
                                 "source_manifest_sha256": identity}
        encoded = json.dumps(report, indent=2) + "\n"
        if args.output:
            with args.output.open("x") as out:
                out.write(encoded)
        else:
            print(encoded, end="")
        return 0
    except (OSError, ValueError, UnicodeError, subprocess.SubprocessError,
            tarfile.TarError, zipfile.BadZipFile) as error:
        print(json.dumps({"status": "FAIL", "error": str(error)}))
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
