#!/usr/bin/env python3
"""Link the generated Sega Rally core and report its bounded native boot frontier.

Run segarally_recompile.py first. Exit 3 means an unimplemented board access;
exit 4 means an unresolved code target. Neither is a successful game boot.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=ROOT / "build/segarally")
    parser.add_argument("--instructions", type=int, default=1_000_000)
    parser.add_argument("--compiler", default=os.environ.get("CXX", "c++"))
    parser.add_argument("--with-tgp", action="store_true", help="Link the audited native Rally TGP generated by segarally_tgp.py")
    parser.add_argument("--with-io", action="store_true", help="Link the Model 2A I/O and EEPROM adapter using the CPU reference-cycle clock")
    parser.add_argument("--with-comm", action="store_true", help="Link the reference communication-board simulation with disconnected peers")
    parser.add_argument("--with-control", action="store_true", help="Connect the IRQ controller and countdown timers at instruction boundaries")
    parser.add_argument("--with-video", action="store_true", help="Connect shared video hardware and verified graphics ROMs (requires --with-tgp)")
    parser.add_argument("--with-screen", action="store_true", help="Schedule screen events and render real display lists (requires --with-control --with-video)")
    parser.add_argument("--with-uart", action="store_true", help="Connect the timed main-board UART with idle RX (requires --with-control; SCSP not connected)")
    parser.add_argument("--capture-frame", action="store_true", help="Save the latest rendered startup frame as boot-frame.ppm (requires --with-screen)")
    args = parser.parse_args()
    output = args.build_dir.resolve()
    if not output.is_relative_to(ROOT / "build"):
        parser.error("--build-dir must be inside this project's ignored build directory")
    if not 1 <= args.instructions <= 1_000_000_000:
        parser.error("--instructions must be 1..1000000000")
    if args.with_video and not args.with_tgp:
        parser.error("--with-video requires --with-tgp for the shared geometry buffer")
    if args.with_screen and not (args.with_control and args.with_video):
        parser.error("--with-screen requires --with-control and --with-video")
    if args.with_uart and not args.with_control:
        parser.error("--with-uart requires --with-control for its ready IRQ pins")
    if args.capture_frame and not args.with_screen:
        parser.error("--capture-frame requires --with-screen")
    try:
        audit = json.loads((output / "coverage.json").read_text())
        if audit.get("board") != "model2a" or not audit.get("native_objects_compiled"):
            raise ValueError("a successful Model2A generation/compile audit is required")
        timing = audit.get("reachability", {})
        if not timing.get("reference_cycle_accounting") or timing.get("reference_cycle_accounting_version") != 1:
            raise ValueError("regenerate native objects with reference-cycle accounting before boot")
        objects = sorted((output / "objects").glob("*.o"))
        if len(objects) != audit["native_object_count"] or not (output / "gen/gen_table.cpp").exists():
            raise ValueError("generated object set does not match the compile audit")
        images = []
        for name in ("program", "main_data"):
            item = audit["images"][name]
            path = (ROOT / item["path"]).resolve()
            if not path.is_relative_to(output):
                raise ValueError("ROM image is outside the audited build directory")
            if hashlib.sha256(path.read_bytes()).hexdigest() != item["sha256"]:
                raise ValueError(f"{name} image differs from the verified import")
            images.append(path)
        compiler = shlex.split(args.compiler)
        executable = output / "srally_boot"
        command = compiler + ["-std=c++20", "-O1", "-fno-fast-math", "-ffp-contract=off", "-Isrc",
            "tools/srally_boot/main.cpp", "src/runtime/model2a_bus.cpp", "src/runtime/cpu.cpp",
            "src/runtime/lockstep.cpp", "src/runtime/model2a_clock.cpp"] + [str(p) for p in objects] + ["-o", str(executable)]
        tgp_images = []
        video_images = []
        if args.with_io:
            command += ["-DM2_SRALLY_IO", "src/runtime/model2_io.cpp", "src/runtime/model2_eeprom.cpp",
                        "src/runtime/model2a_io.cpp"]
        if args.with_comm:
            command += ["-DM2_SRALLY_COMM", "src/runtime/model2a_comm.cpp", "src/runtime/comm_board.cpp"]
        if args.with_control:
            command += ["-DM2_SRALLY_CONTROL", "src/runtime/model2a_control.cpp"]
        if args.with_screen:
            command += ["-DM2_SRALLY_SCREEN"]
        if args.with_uart:
            command += ["-DM2_SRALLY_UART", "src/runtime/model2_uart.cpp", "src/runtime/model2a_uart.cpp"]
        if args.with_tgp:
            tgp_dir = output / "tgp"
            tgp_audit = json.loads((tgp_dir / "audit.json").read_text())
            if not tgp_audit["native_code_compiled"] or tgp_audit["romset"] != audit["romset"]:
                raise ValueError("a matching native TGP audit is required")
            for name in ("copro_tgp_tables", "copro_data"):
                entry = tgp_audit["images"][name]
                path = (ROOT / entry["path"]).resolve()
                if not path.is_relative_to(tgp_dir) or hashlib.sha256(path.read_bytes()).hexdigest() != entry["sha256"]:
                    raise ValueError(f"{name} differs from the verified TGP import")
                tgp_images.append(path)
            command += ["-DM2_SRALLY_TGP", "src/runtime/tgp.cpp", "src/runtime/m2_tgp_board.cpp",
                        str(tgp_dir / "program.cpp")]
        if args.with_video:
            video_dir = output / "video"
            video_audit = json.loads((video_dir / "audit.json").read_text())
            manifest = ROOT / "config/segarally_video.json"
            if (video_audit.get("romset") != audit["romset"] or
                video_audit.get("manifest_sha256") != hashlib.sha256(manifest.read_bytes()).hexdigest()):
                raise ValueError("a matching verified video import is required")
            for name in ("polygons", "textures"):
                entry = video_audit["images"][name]
                path = (ROOT / entry["path"]).resolve()
                if not path.is_relative_to(video_dir) or hashlib.sha256(path.read_bytes()).hexdigest() != entry["sha256"]:
                    raise ValueError(f"{name} differs from the verified video import")
                video_images.append(path)
            command += ["-DM2_SRALLY_VIDEO", "src/runtime/model2a_video.cpp", "src/runtime/video.cpp",
                        "src/runtime/raster.cpp", "src/runtime/geo.cpp"]
        with (output / "boot-build.log").open("w") as log:
            subprocess.run(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, check=True)
        capture = [str(output / "boot-frame.ppm")] if args.capture_frame else []
        result = subprocess.run([str(executable), *map(str, images), str(args.instructions), *map(str, tgp_images), *map(str, video_images), *capture],
            cwd=ROOT, capture_output=True, text=True, timeout=180)
        transcript = result.stdout + result.stderr
        (output / "boot.txt").write_text(transcript)
        report = {"native_core_linked": True, "full_game_boot_verified": False,
                  "native_tgp_linked": args.with_tgp,
                  "native_io_linked": args.with_io,
                  "board_clock_connected": args.with_io or args.with_control,
                  "native_comm_linked": args.with_comm, "comm_peer_connected": False,
                  "native_control_linked": args.with_control,
                  "native_video_linked": args.with_video,
                  "video_clock_connected": args.with_screen, "uart_connected": args.with_uart,
                  "scsp_sound_board_connected": False,
                  "clock_source": "pinned_mame_i960_cycles_at_25mhz", "pcb_timing_verified": False,
                  "instruction_limit": args.instructions, "exit_code": result.returncode,
                  "image_sha256": {name: audit["images"][name]["sha256"] for name in ("program", "main_data")},
                  "transcript": transcript}
        for line in result.stdout.splitlines():
            if line.startswith("status="):
                report["frontier"] = dict(token.split("=", 1) for token in line.split() if "=" in token)
            elif line.startswith("frame_capture "):
                report["frame_capture"] = {"path": capture[0],
                    "sha256": hashlib.sha256(Path(capture[0]).read_bytes()).hexdigest(),
                    **dict(token.split("=", 1) for token in line.split() if "=" in token)}
        (output / "boot.json").write_text(json.dumps(report, indent=2) + "\n")
        print(transcript, end="")
        print(f"Boot frontier report: {output / 'boot.json'}")
        return result.returncode
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as failure:
        print(f"segarally_boot: {failure}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
