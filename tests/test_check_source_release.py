#!/usr/bin/env python3
"""ROM-free Git/export fixtures for the source publication boundary."""
import contextlib
import importlib.util
import io
import json
from pathlib import Path
import subprocess
import tarfile
import tempfile
import unittest
from unittest.mock import patch
import warnings
import zipfile

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("source_release", ROOT / "scripts/check_source_release.py")
release = importlib.util.module_from_spec(spec)
spec.loader.exec_module(release)


class SourceRelease(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.repo = self.root / "repo"
        self.repo.mkdir()
        self.git("init", "-q")
        self.git("config", "user.name", "Fixture")
        self.git("config", "user.email", "fixture@example.invalid")
        self.commit({"README.md": b"Public source fixture\n", "src/main.cpp": b"int main() { return 0; }\n"})

    def tearDown(self):
        self.temp.cleanup()

    def git(self, *args):
        return subprocess.check_output(["git", "-C", str(self.repo), *args], stderr=subprocess.PIPE)

    def commit(self, files):
        for name, data in files.items():
            path = self.repo / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        self.git("add", "--all")
        self.git("commit", "-q", "-m", "fixture")

    def manifest(self):
        return release.source_manifest(self.repo)

    def test_head_tree_is_deterministic_and_not_a_working_directory_export(self):
        first = self.manifest()
        (self.repo / "personal.zip").write_bytes(b"private local data")
        (self.repo / "README.md").write_bytes(b"uncommitted local change")
        second = self.manifest()
        self.assertEqual(release.canonical(first), release.canonical(second))
        export = self.root / "export"
        export.mkdir()
        data = self.git("archive", "HEAD")
        with tarfile.open(fileobj=io.BytesIO(data)) as archive:
            for entry in archive:
                if entry.isfile():
                    target = export / entry.name
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(archive.extractfile(entry).read())
        release.check_files(first, release.directory_files(export))
        (export / "personal.zip").write_bytes(b"private local data")
        with self.assertRaisesRegex(ValueError, "export paths differ"):
            release.check_files(first, release.directory_files(export))

    def test_tracked_rom_is_rejected_even_if_ignore_rule_exists(self):
        self.commit({".gitignore": b"*.zip\n"})
        (self.repo / "game.zip").write_bytes(b"synthetic forbidden archive")
        self.git("add", "--force", "game.zip")
        self.git("commit", "-q", "-m", "fixture")
        with self.assertRaisesRegex(ValueError, "filename"):
            self.manifest()

    def test_renamed_binary_and_generated_game_source_are_rejected(self):
        self.commit({"innocent.txt": b"not-text\0synthetic"})
        with self.assertRaisesRegex(ValueError, "binary content"):
            self.manifest()
        for name, data in [("src/ordinary.cpp", b"// Generated by " + b"m2recomp. Derived from the game\n"),
                           ("src/ordinary.cpp", b"void " + b"fn_005a0000() {}\n"),
                           ("elsewhere/chunk_002.cpp", b"synthetic fixture\n"),
                           ("Public.app/Contents/file.txt", b"synthetic fixture\n")]:
            with self.subTest(name=name), self.assertRaises(ValueError):
                release.classify(name, data)

    def test_reviewed_exceptions_are_narrow_and_not_general_binary_permissions(self):
        shader = release.SHADER_HEADERS[0] + b" do not edit.\n#pragma once\n"
        self.assertEqual(release.classify(release.SHADER_PATH, shader), "project_hlsl_shader_header")
        with self.assertRaisesRegex(ValueError, "provenance"):
            release.classify(release.SHADER_PATH, b"unreviewed replacement\n")
        with self.assertRaisesRegex(ValueError, "Gradle"):
            release.classify(release.GRADLE_PATH, b"unreviewed archive")
        with self.assertRaisesRegex(ValueError, "filename"):
            release.classify("another-wrapper.jar", b"synthetic archive")

    def test_curated_screenshot_requires_exact_path_and_bytes(self):
        # Invented data exercises the identity boundary, not game-image content.
        path = "docs/images/invented-screen.png"
        data = b"\x89PNG\r\n\x1a\n" + b"self-authored screenshot identity fixture"
        with patch.object(release, "CURATED_SCREENSHOTS", {path: release.sha256(data)}):
            self.assertEqual(release.classify(path, data), "curated_documentation_screenshot")
            with self.assertRaisesRegex(ValueError, "screenshot bytes"):
                release.classify(path, data + b"changed")
            for unknown in ("docs/images/other.png", "elsewhere/invented-screen.png"):
                with self.subTest(path=unknown), self.assertRaisesRegex(ValueError, "filename"):
                    release.classify(unknown, data)
            self.commit({path: data})
            manifest = self.manifest()
            row = next(r for r in manifest["files"] if r["path"] == path)
            self.assertEqual(row["classification"], "curated_documentation_screenshot")
            self.assertEqual(row["sha256"], release.sha256(data))
            self.commit({path: data + b"changed"})
            with self.assertRaisesRegex(ValueError, "screenshot bytes"):
                self.manifest()

    def test_credential_failure_never_includes_the_value(self):
        token = b"ghp_" + b"A" * 36
        with self.assertRaises(ValueError) as caught:
            release.classify("settings.txt", token)
        self.assertNotIn(token.decode(), str(caught.exception))
        self.assertIn("credential marker", str(caught.exception))
        for prefix in (b"", b"ENCRYPTED "):
            key = b"-----BEGIN " + prefix + b"PRIVATE KEY-----\nsynthetic\n"
            with self.subTest(prefix=prefix), self.assertRaisesRegex(ValueError, "private-key"):
                release.classify("settings.txt", key)

    def test_exact_archives_accept_git_prefix_and_reject_added_or_changed_files(self):
        manifest = self.manifest()
        expected = {row["path"] for row in manifest["files"]}
        for prefix in ("", "public-source/"):
            path = self.root / ("prefixed.tar.gz" if prefix else "bare.tar")
            args = ["archive", "--format=tar.gz" if prefix else "--format=tar"]
            if prefix:
                args.append("--prefix=" + prefix)
            path.write_bytes(self.git(*args, "HEAD"))
            files, digest = release.archive_files(path, expected)
            release.check_files(manifest, files)
            self.assertEqual(digest, release.sha256(path.read_bytes()))
        path = self.root / "source.zip"
        with zipfile.ZipFile(path, "w") as archive:
            for row in manifest["files"]:
                archive.writestr("source/" + row["path"], (self.repo / row["path"]).read_bytes())
        files, _ = release.archive_files(path, expected)
        release.check_files(manifest, files)
        files["README.md"] = b"changed source\n"
        with self.assertRaisesRegex(ValueError, "export bytes differ"):
            release.check_files(manifest, files)
        files["capture.wav"] = b"not part of source\n"
        with self.assertRaisesRegex(ValueError, "export paths differ"):
            release.check_files(manifest, files)

    def test_archive_traversal_duplicate_and_symlink_are_rejected(self):
        for member in ("../outside.txt", "/outside.txt", "a/../outside.txt", "a\\outside.txt"):
            path = self.root / "bad.zip"
            with zipfile.ZipFile(path, "w") as archive:
                archive.writestr(member, b"synthetic")
            with self.subTest(member=member), self.assertRaises(ValueError):
                release.archive_files(path, set())
        path = self.root / "link.tar"
        with tarfile.open(path, "w") as archive:
            entry = tarfile.TarInfo("link")
            entry.type = tarfile.SYMTYPE
            entry.linkname = "outside"
            archive.addfile(entry)
        with self.assertRaisesRegex(ValueError, "link or special"):
            release.archive_files(path, set())
        path = self.root / "duplicate.zip"
        with zipfile.ZipFile(path, "w") as archive, warnings.catch_warnings():
            warnings.simplefilter("ignore", UserWarning)
            archive.writestr("same.txt", b"first")
            archive.writestr("same.txt", b"second")
        with self.assertRaisesRegex(ValueError, "duplicate"):
            release.archive_files(path, {"same.txt"})
        export = self.root / "symlink-export"
        export.mkdir()
        (export / "link").symlink_to(self.repo / "README.md")
        with self.assertRaisesRegex(ValueError, "symlink"):
            release.directory_files(export)

    def test_bounds_apply_before_archive_member_read(self):
        path = self.root / "large.tar"
        entry = tarfile.TarInfo("large.txt")
        entry.size = release.MAX_FILE + 1
        path.write_bytes(entry.tobuf() + b"\0" * 1024)
        with self.assertRaisesRegex(ValueError, "limits"):
            release.archive_files(path, {"large.txt"})

    def test_tree_limit_counts_repeated_blob_at_every_export_path(self):
        data = (self.repo / "README.md").read_bytes()
        self.commit({"copy-one.txt": data, "copy-two.txt": data})
        manifest = self.manifest()
        unique = {row["git_blob"]: row["bytes"] for row in manifest["files"]}
        cap = sum(unique.values()) + 1
        self.assertLess(cap, sum(row["bytes"] for row in manifest["files"]))
        with patch.object(release, "MAX_TOTAL", cap), self.assertRaisesRegex(ValueError, "byte-size"):
            self.manifest()

    def test_unix_zip_special_files_and_directory_payload_are_rejected(self):
        path = self.root / "special.zip"
        for kind in (0o010000, 0o020000, 0o060000, 0o120000, 0o140000):
            entry = zipfile.ZipInfo("entry")
            entry.create_system = 3
            entry.external_attr = (kind | 0o644) << 16
            with zipfile.ZipFile(path, "w") as archive:
                archive.writestr(entry, b"synthetic")
            with self.subTest(kind=kind), self.assertRaisesRegex(ValueError, "link or special"):
                release.archive_files(path, {"entry"})
        with zipfile.ZipFile(path, "w") as archive:
            archive.writestr("hidden/", b"unexpected payload")
        with self.assertRaisesRegex(ValueError, "payload"):
            release.archive_files(path, set())

    def test_cli_binds_archive_to_manifest_and_never_overwrites_output(self):
        path = self.root / "source.tar"
        path.write_bytes(self.git("archive", "HEAD"))
        output = self.root / "report.json"
        args = ["--repo", str(self.repo), "--archive", str(path), "--output", str(output)]
        self.assertEqual(release.main(args), 0)
        report = json.loads(output.read_text())
        self.assertEqual(report["archive"]["source_manifest_sha256"], report["manifest_sha256"])
        old = output.read_bytes()
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(release.main(args), 1)
        self.assertEqual(output.read_bytes(), old)


if __name__ == "__main__":
    unittest.main()
